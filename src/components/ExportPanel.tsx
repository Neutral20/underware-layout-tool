import { zipSync, strToU8 } from "fflate";
import { useEffect, useMemo, useState } from "react";
import { buildExportPlan, partsCsv, type RenderJob } from "../render/plan";
import { MOUNT_STYLES, mountById } from "../render/mounts";
import { cancelAll, render } from "../render/service";
import type { Board, PartType } from "../model/types";
import { printerFor } from "../model/printers";

type Status = { state: "queued" } | { state: "rendering" } | { state: "done"; ms: number; bytes: number } | { state: "failed"; error: string };

const CREDITS = `Generated by Underware Layout Tool.

Part models: QuackWorks Underware 2.0 by Hands on Katie and BlackjackDuck
(Andy Levesque), https://github.com/AndyLevesque/QuackWorks, and
Underware for openGrid by David D,
https://www.printables.com/model/1214427-underware-for-opengrid-manage-your-cables-lite-ly
and Monokini by Pedro Leite, https://github.com/pleite/Monokini
All licensed CC BY-NC-SA 4.0. Rendered with OpenSCAD and BOSL2.

parts.csv lists each file, how many to print, and the parameters used.
File names end in _xN where N is the quantity to print.

Straights longer than the printer's bed are cut into segments on cell
lines. Print every segment listed and lay them end to end; each one clips
(or snaps) to the grid on its own, so no joiner is needed.
`;

interface Props {
  board: Board;
  partTypes: PartType[];
  onMount(id: string): void;
}

export function ExportPanel({ board, partTypes, onMount }: Props) {
  const plan = useMemo(() => buildExportPlan(board, partTypes), [board, partTypes]);
  const [running, setRunning] = useState(false);
  const [status, setStatus] = useState<Record<string, Status>>({});
  const [startedAt, setStartedAt] = useState<number | null>(null);
  const [now, setNow] = useState(Date.now());
  const mount = mountById(board.channelMount);
  const hasChannels = partTypes.some((t) => t.category === "underware-channel" && board.placements.some((p) => p.partTypeId === t.id));
  const blocked = hasChannels && !mount.available;

  useEffect(() => {
    if (!running) return;
    const t = setInterval(() => setNow(Date.now()), 500);
    return () => clearInterval(t);
  }, [running]);
  useEffect(() => () => cancelAll(), []);

  const totalPieces = plan.jobs.reduce((n, j) => n + j.quantity, 0);

  const run = async () => {
    setRunning(true);
    setStartedAt(Date.now());
    setStatus(Object.fromEntries(plan.jobs.map((j) => [j.key, { state: "queued" } as Status])));
    const files: Record<string, Uint8Array> = {};
    const errors: string[] = [];
    let cancelled = false;

    await Promise.all(
      plan.jobs.map(async (j: RenderJob) => {
        const r = await render(j.scadPath, j.defines, () =>
          setStatus((s) => ({ ...s, [j.key]: { state: "rendering" } })),
        );
        if (r.ok) {
          files[j.fileName] = new Uint8Array(r.stl);
          setStatus((s) => ({ ...s, [j.key]: { state: "done", ms: r.ms, bytes: r.stl.byteLength } }));
        } else {
          if (r.error === "Cancelled") cancelled = true;
          errors.push(`${j.fileName}: ${r.error}`);
          setStatus((s) => ({ ...s, [j.key]: { state: "failed", error: r.error } }));
        }
      }),
    );
    setRunning(false);
    if (cancelled || Object.keys(files).length === 0) return;

    const zip = zipSync(
      {
        ...Object.fromEntries(Object.entries(files).map(([k, v]) => [`stl/${k}`, [v, { level: 6 }] as [Uint8Array, { level: 6 }]])),
        "parts.csv": strToU8(partsCsv(plan)),
        "layout.json": strToU8(JSON.stringify({ version: 1, board, partTypes }, null, 2)),
        "README.txt": strToU8(CREDITS),
        ...(errors.length ? { "errors.txt": strToU8(errors.join("\n\n") + "\n") } : {}),
      },
      { level: 0 },
    );
    const a = document.createElement("a");
    a.href = URL.createObjectURL(new Blob([zip], { type: "application/zip" }));
    a.download = `${board.name.replace(/[^\w-]+/g, "_") || "layout"}_stls.zip`;
    a.click();
    setTimeout(() => URL.revokeObjectURL(a.href), 10_000);
  };

  const cancel = () => cancelAll();

  const done = Object.values(status).filter((s) => s.state === "done" || s.state === "failed").length;

  return (
    <section>
      <h2>Export STLs</h2>
      {plan.jobs.length === 0 && plan.manual.length === 0 ? (
        <p className="muted">Add parts to the board first.</p>
      ) : (
        <>
          <p className="muted">
            {plan.jobs.length} unique STL{plan.jobs.length === 1 ? "" : "s"} to render, {totalPieces} pieces to print.
            {board.pitchMm === 28 ? " Channels render at the 28 mm openGrid pitch." : ""} Renders already done this session are reused.
          </p>
          {plan.runs.length ? (
            <p className="muted">
              Cut to fit the {printerFor(board.printer).name}:{" "}
              {plan.runs.map((r) => `${r.name} ${r.lengthCells} cells → ${r.segments.join(" + ")}${r.quantity > 1 ? ` (×${r.quantity})` : ""}`).join("; ")}.
              Segments butt together on cell lines.
            </p>
          ) : null}
          {plan.manual.length ? (
            <p className="muted">Custom parts aren't generated: {plan.manual.map((m) => `${m.name} ×${m.quantity}`).join(", ")}.</p>
          ) : null}
          {MOUNT_STYLES.length > 1 ? (
          <label className="field">
            <span>Channel mount</span>
            <select value={mount.id} onChange={(e) => onMount(e.target.value)} disabled={running}>
              {MOUNT_STYLES.map((m) => (
                <option key={m.id} value={m.id}>
                  {m.label}
                  {m.available ? "" : " (not available yet)"}
                </option>
              ))}
            </select>
          </label>
          ) : null}
          {blocked ? <p className="error-text">{mount.note}</p> : null}
          <div className="row buttons">
            {running ? (
              <button className="danger" onClick={cancel}>
                Cancel
              </button>
            ) : (
              <button onClick={run} disabled={plan.jobs.length === 0 || blocked}>
                Generate STL zip
              </button>
            )}
          </div>
          {startedAt && Object.keys(status).length ? (
            <>
              <p className="muted">
                {done}/{plan.jobs.length} rendered{running ? ` · ${Math.round((now - startedAt) / 1000)} s` : ""}. Each part takes 5 to 30 s.
              </p>
              <ul className="jobs">
                {plan.jobs.map((j) => {
                  const s = status[j.key];
                  return (
                    <li key={j.key} className={s?.state}>
                      <span className="job-name">{j.fileName}</span>
                      <span className="job-state">
                        {s?.state === "done" ? `${(s.ms / 1000).toFixed(0)} s` : s?.state === "failed" ? "failed" : s?.state ?? ""}
                      </span>
                      {s?.state === "failed" ? <div className="error-text">{s.error}</div> : null}
                    </li>
                  );
                })}
              </ul>
            </>
          ) : null}
        </>
      )}
    </section>
  );
}
